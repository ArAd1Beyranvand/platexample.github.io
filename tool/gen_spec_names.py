#!/usr/bin/env python3
"""Generates lib/newdesign/data/spec_names.g.dart (spec and theme names).

The playground prints Dart code for the plate on screen, and the catalogue
entries hold spec objects, not the name a developer would type. This scans the
country packages this app depends on for public `static final|const PlateSpec`
and `PlateTheme` fields on public classes and emits identity maps from object
to name, plus
each package's git URL (its pubspec `homepage`).

Names the analyzer rejects (classes the barrel does not export) are dropped,
so the output always compiles. Run from the app root:

    python3 tool/gen_spec_names.py
"""
import pathlib
import re
import subprocess

APP = pathlib.Path(__file__).resolve().parent.parent
OUT = APP / 'lib/newdesign/data/spec_names.g.dart'

CLASS = re.compile(r'^(?:abstract )?(?:final )?class ([A-Z]\w*)', re.M)
FIELD = re.compile(r'(@Deprecated\([^;]*?\)\s*)?^\s+static (?:final|const) (PlateSpec|PlateTheme) ([a-z]\w*)\s*=', re.M)


def path_deps():
    text = (APP / 'pubspec.yaml').read_text()
    text = text[text.index('\ndependencies:'):text.index('\ndev_dependencies:')]
    deps = re.findall(r'^  (\w+):\n    path: (\S+)', text, re.M)
    return [(name, (APP / path).resolve()) for name, path in deps]


def homepage(pkg_dir):
    m = re.search(r'^homepage:\s*(\S+)', (pkg_dir / 'pubspec.yaml').read_text(), re.M)
    return m.group(1) if m else None


def names(pkg_dir):
    out = []
    for f in sorted((pkg_dir / 'lib').rglob('*.dart')):
        text = f.read_text()
        classes = [(m.start(), m.group(1)) for m in CLASS.finditer(text)]
        for m in FIELD.finditer(text):
            owner = [c for pos, c in classes if pos < m.start()]
            if owner and not m.group(1):
                out.append((m.group(2), f'{owner[-1]}.{m.group(3)}'))
    return out


def barrel(pkg, pkg_dir):
    if (pkg_dir / f'lib/{pkg}.dart').exists():
        return f'{pkg}.dart'
    return sorted(p.name for p in (pkg_dir / 'lib').glob('*.dart'))[0]


def render(deps, entries):
    lines = [
        '// GENERATED by tool/gen_spec_names.py. Do not edit.',
        '// ignore_for_file: directives_ordering',
        "import 'package:plate_core/plate_core.dart';",
    ]
    lines += [f"import 'package:{p}/{barrel(p, d)}';" for p, d in deps if entries.get(p)]
    lines += ['', '/// The Dart name of every spec a country package exposes publicly.',
              'final Map<PlateSpec, String> specNames = Map<PlateSpec, String>.identity()']
    lines += [f"  ..putIfAbsent({n}, () => '{n}')" for ns in entries.values() for k, n in ns if k == 'PlateSpec']
    lines[-1] += ';'
    lines += ['', '/// The Dart name of every theme a country package exposes publicly.',
              'final Map<PlateTheme, String> themeNames = Map<PlateTheme, String>.identity()']
    lines += [f"  ..putIfAbsent({n}, () => '{n}')" for ns in entries.values() for k, n in ns if k == 'PlateTheme']
    lines[-1] += ';'
    lines += ['', "/// Each package's git repository, from its pubspec `homepage`.",
              'const Map<String, String> packageRepos = <String, String>{']
    for p, d in deps:
        url = homepage(d)
        if url:
            lines.append(f"  '{p}': '{url}',")
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    deps = [('plate_core', (APP / '../plate_core').resolve())] + path_deps()
    seen = set()
    entries = {}
    for p, d in deps:
        if p in ('plate_core', 'plate_keypad'):
            continue
        entries[p] = [n for n in dict.fromkeys(names(d)) if n not in seen]
        seen.update(entries[p])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    for _ in range(5):
        OUT.write_text(render(deps, entries))
        res = subprocess.run(['dart', 'analyze', str(OUT)], cwd=APP, capture_output=True, text=True)
        bad = set()
        for line in res.stdout.splitlines():
            m = re.search(r':(\d+):\d+ - .*(undefined|isn\'t defined|not_a_constant|const_)', line, re.I)
            if m and line.strip().startswith('error'):
                bad.add(int(m.group(1)))
        if not bad:
            break
        text = OUT.read_text().splitlines()
        drop = {re.sub(r'^\.\.putIfAbsent\(([^,]+),.*', r'\1', text[i - 1].strip()) for i in bad}
        drop = {(k, n) for ns in entries.values() for k, n in ns if n in drop}
        entries = {p: [n for n in ns if n not in drop] for p, ns in entries.items()}
    # An alias (`taxi = private`) is one object under two names; putIfAbsent
    # keeps the first.
    print(f'{sum(map(len, entries.values()))} names, {len(deps)} packages -> {OUT.relative_to(APP)}')


if __name__ == '__main__':
    main()
